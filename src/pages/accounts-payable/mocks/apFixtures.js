export const buildExceptions = () =>
  INVOICES.filter((invoice) => invoice.status === INVOICE_STATUS.EXCEPTION).map((invoice) => ({
    id: `EXC-${invoice.id.slice(-5)}`,
    invoiceId: invoice.id,
    vendorId: invoice.vendorId,
    vendorName: vendorName(invoice.vendorId),
    amount: invoice.amount,
    type: invoice.exceptionType,
    status: EXCEPTION_STATUS.OPEN,
    submittedDate: invoice.submittedDate,
    detail:
      invoice.exceptionType === EXCEPTION_TYPES.DUPLICATE_INVOICE
        ? `Matches existing invoice ${invoice.duplicateOf}`
        : invoice.exceptionType === EXCEPTION_TYPES.MISSING_PO
        ? "No purchase order referenced on the invoice"
        : invoice.exceptionType === EXCEPTION_TYPES.MISSING_GRN
        ? "No goods receipt note recorded against the referenced PO"
        : invoice.exceptionType === EXCEPTION_TYPES.TAX_DISCREPANCY
        ? "Invoice tax amount does not match jurisdiction tax rules"
        : invoice.exceptionType === EXCEPTION_TYPES.QUANTITY_MISMATCH
        ? `Invoice quantity does not match PO ${invoice.poNumber} receipt quantity`
        : `Invoice unit price does not match PO ${invoice.poNumber} rate`,
  }));

