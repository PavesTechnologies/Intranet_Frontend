const INR = { code: "INR", symbol: "₹" };

let nextIssueId = 1;
function issue({ source, type, severity, result, description, status = ISSUE_STATUS.OPEN, resolvedBy = "", resolvedAt = "" }) {
  return {
    id: `iss-${nextIssueId++}`,
    issueSource: source,
    issueType: type,
    severity,
    result,
    description,
    status,
    resolvedBy,
    resolvedAt,
  };
}

function lines(items) {
  return items.map((item, index) => ({
    id: `line-${index + 1}`,
    lineNumber: index + 1,
    ...item,
    lineAmount: Math.round((item.quantity * item.unitPrice + item.taxAmount) * 100) / 100,
  }));
}

function attachment(fileName, fileType, uploadedAt) {
  return { id: `att-${fileName}`, fileName, fileType, uploadedAt, fileUrl: "" };
}

